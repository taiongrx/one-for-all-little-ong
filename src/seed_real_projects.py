def seed_if_empty(force: bool = False) -> Dict[str, Any]:
    """
    Populates the database with the real discovered machine projects
    on first initialization or when force=True.
    """
    init_databases()
    existing, db_status = query_all_apps()
    already_seeded = get_meta("initial_seed_v1") == "1"
    if (existing or already_seeded) and not force:
        return {"seeded": 0, "total": len(existing), "db_status": db_status}

    count = 0
    for proj in REAL_DISCOVERED_PROJECTS:
        ok, err = validate_application_payload(proj)
        if not ok:
            raise ValueError(err)
        upsert_app_record(proj, sync_cloud=True)
        count += 1

    set_meta("initial_seed_v1", "1")
    updated, db_status = query_all_apps()
    return {"seeded": count, "total": len(updated), "db_status": db_status}
